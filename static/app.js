function esc(s){return String(s).replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]))}
function linkify(s){return esc(s).replace(/https?:\/\/[^\s)]+/g,u=>`<a href="${u}" target="_blank" rel="noopener">${u}</a>`)}
async function api(path, body){
  const r = await fetch(path, body ? {method:"POST", headers:{"Content-Type":"application/json"}, body:JSON.stringify({...body, lang, sid})} : {});
  if (!r.ok) throw new Error((await r.json().catch(()=>({}))).detail || r.status);
  return r.json();
}
function profile(){
  const age = parseInt($("#p_age").value, 10);
  return {education:$("#p_edu").value, age:isNaN(age)?null:age, interests:$("#p_int").value, target_role:$("#p_role").value, resume_text:$("#resume").value};
}
function saveProfile(){ ["p_edu","p_age","p_int","p_role"].forEach(id=>store("ks_"+id, $("#"+id).value)); }
function feedback(el, ref){
  const d = document.createElement("div"); d.className="fb";
  d.innerHTML = `${esc(L().helpful)} <button class="ghost">${L().yes}</button><button class="ghost">${L().no}</button>`;
  const [y,n] = d.querySelectorAll("button");
  const send = kind => { api("/api/event",{kind, ref}); d.textContent = L().thanks; };
  y.onclick = () => send("feedback_up"); n.onclick = () => send("feedback_down");
  el.appendChild(d);
}

function applyLang(){
  document.documentElement.lang = lang; $("#lang").value = lang;
  document.querySelectorAll("[data-i]").forEach(e => e.textContent = L()[e.dataset.i]);
  $("#msg").placeholder = L().msg_ph; $("#resume").placeholder = L().resume_ph; $("#ans").placeholder = L().ans_ph;
  $("#chips").innerHTML = ""; L().chips.forEach(c => { const b=document.createElement("button"); b.type="button"; b.textContent=c; b.onclick=()=>{ if(c===L().chips[0] && !$("#resume").value){ tab("resume"); return; } send(c); }; $("#chips").appendChild(b); });
  fetch(`/api/roles?lang=${lang}`).then(r=>r.json()).then(rs=>{ const cur = store("ks_p_role") || "software-developer"; $("#p_role").innerHTML = rs.map(r=>`<option value="${r.id}">${esc(r.title)}</option>`).join(""); $("#p_role").value = cur; loadQ(); });
}
function tab(name){
  document.querySelectorAll("nav button").forEach(b=>b.classList.toggle("on", b.dataset.tab===name));
  document.querySelectorAll(".tab").forEach(s=>s.classList.toggle("hidden", s.id!=="tab-"+name));
}

function bubble(text, who, steps){
  const d = document.createElement("div"); d.className = "m " + who; d.innerHTML = linkify(text);
  if (steps && steps.length){ const s=document.createElement("div"); s.className="steps"; s.textContent = L().steps + ": " + steps.map(x=>x.tool).join(" → "); d.appendChild(s); }
  $("#log").appendChild(d); $("#log").scrollTop = 1e9; return d;
}
async function send(text){
  if (!text.trim()) return;
  bubble(text, "u"); const wait = bubble(L().thinking, "a");
  try {
    const r = await api("/api/chat", {message:text, history, profile:profile()});
    wait.remove(); const b = bubble(r.reply, "a", r.steps); feedback(b, "chat");
    history.push({role:"user", content:text}, {role:"assistant", content:r.reply});
  } catch(e){ wait.textContent = L().err; }
}

async function checkResume(){
  const btn = $("#check"); btn.disabled = true;
  try {
    const r = await api("/api/resume", {resume_text:$("#resume").value, target_role:$("#p_role").value});
    const out = $("#resume_out");
    out.innerHTML = `<p>${esc(L().score)}</p><div class="score">${r.score}/100</div><div class="bar"><i style="width:${r.score}%"></i></div>
      <h2>${esc(L().fixes)}</h2><ul>${r.fixes.map(f=>`<li>${esc(f)}</li>`).join("")}</ul>
      ${r.skills_found.length?`<p><b>${esc(L().skills_found)}:</b> ${r.skills_found.map(s=>`<span class="tag">${esc(s)}</span>`).join("")}</p>`:""}
      ${r.ai_rewrite?`<h2>${esc(L().ai)}</h2><div class="ai">${esc(r.ai_rewrite)}</div>`:""}`;
    feedback(out, "resume");
  } catch(e){ $("#resume_out").textContent = e.message || L().err; }
  btn.disabled = false;
}

async function loadQ(){
  const r = await (await fetch(`/api/interview/${encodeURIComponent($("#p_role").value || "software-developer")}/${qIndex}?lang=${lang}`)).json();
  $("#q").textContent = `${r.index+1}/${r.total} · ${r.question}`; $("#ans").value = ""; $("#ans_out").innerHTML = "";
}
async function submitAns(){
  const btn = $("#submit_ans"); btn.disabled = true;
  try {
    const r = await api("/api/interview/answer", {role:$("#p_role").value, index:qIndex, answer:$("#ans").value});
    const out = $("#ans_out");
    out.innerHTML = `<div class="score">${r.score}/10</div><ul>${r.tips.map(t=>`<li>${esc(t)}</li>`).join("")}</ul>${r.ai_feedback?`<div class="ai">${esc(r.ai_feedback)}</div>`:""}`;
    feedback(out, "interview");
  } catch(e){ $("#ans_out").textContent = L().err; }
  btn.disabled = false;
}

async function findOpps(){
  const p = profile();
  try {
    const r = await api("/api/opportunities", {education:p.education, age:p.age, interests:p.interests + " " + p.target_role});
    const out = $("#opps_out");
    out.innerHTML = r.items.map(o=>`<div class="opp"><span class="tag">${esc(o.type)}</span><span class="tag">${esc(o.cost)}</span><b>${esc(o.name)}</b><small>${esc(o.provider)}</small><p>${esc(o.summary)}</p><a href="/go/${o.id}?sid=${sid}&lang=${lang}" target="_blank" rel="noopener">${esc(L().open)} →</a></div>`).join("");
    feedback(out, "opportunities");
  } catch(e){ $("#opps_out").textContent = L().err; }
}
async function roadmap(){
  const p = profile();
  try {
    const r = await api("/api/roadmap", {target_role:p.target_role, current_skills:p.interests + " " + p.resume_text});
    const out = $("#opps_out");
    out.innerHTML = `<h2>${esc(r.role)}</h2>${r.have.length?`<p>✅ ${r.have.map(esc).join(", ")}</p>`:""}<ol>${r.steps.map(s=>`<li>${esc(s)}</li>`).join("")}</ol><ul>${r.resources.map(x=>`<li><a href="${esc(x.url)}" target="_blank" rel="noopener">${esc(x.name)}</a></li>`).join("")}</ul>`;
    feedback(out, "roadmap");
  } catch(e){ $("#opps_out").textContent = L().err; }
}

